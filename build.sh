# Enhanced configuration discovery with priority system
load_configuration() {
    local config_file=""
    local config_source=""
    
    # Initialize with defaults first
    for key in "${!default_config[@]}"; do
        declare -g "$key"="${default_config[$key]}"
    done
    
    # Priority 1: --conf=path command-line option (set via opt_conf from options parsing)
    if [[ -n "${opt_conf:-}" ]]; then
        config_file="$opt_conf"
        config_source="command-line option --conf"
    # Priority 2: BUILDSH_CONF_FILE environment variable
    elif [[ -n "${BUILDSH_CONF_FILE:-}" ]]; then
        config_file="$BUILDSH_CONF_FILE"
        config_source="environment variable BUILDSH_CONF_FILE"
    # Priority 3: Local directory discovery (default behavior)
    else
        config_file="./build.conf"
        config_source="local directory discovery"
    fi
    
    # Try to load from discovered config file
    if [[ -f "$config_file" ]]; then
        # Resolve to absolute path for cleaner display
        local abs_config_file
        abs_config_file=$(readlink -f "$config_file" 2>/dev/null) || abs_config_file="$config_file"
        
        printf "%sLoading configuration from: %s%s\n" "$blue" "$abs_config_file" "$x" >&2
        printf "%sConfiguration source: %s%s\n" "$blue" "$config_source" "$x" >&2
        
        # Source the config file safely
        while IFS='=' read -r key value; do
            # Skip comments and empty lines
            [[ "$key" =~ ^[[:space:]]*# ]] && continue
            [[ -z "${key// }" ]] && continue
            
            # Remove leading/trailing whitespace and quotes
            key=$(echo "$key" | xargs)
            value=$(echo "$value" | xargs | sed 's/^["'\'']//' | sed 's/["'\'']$//')
            
            # Set the variable if it's a known config key
            if [[ -n "${default_config[$key]:-}" ]]; then
                declare -g "$key"="$value"
                [[ "$opt_verbose" == true ]] && printf "  %s%s%s = %s\n" "$green" "$key" "$x" "$value" >&2
            fi
        done < <(grep -E '^[^#]*=' "$config_file" 2>/dev/null || true)
        
        return 0
    else
        # Handle missing config file based on source
        if [[ "$config_source" == "command-line option --conf" ]]; then
            printf "%sERROR:%s Configuration file specified via --conf not found: %s%s\n" "$red" "$x" "$config_file" "$x" >&2
            return 1
        elif [[ "$config_source" == "environment variable BUILDSH_CONF_FILE" ]]; then
            printf "%sERROR:%s Configuration file specified via BUILDSH_CONF_FILE not found: %s%s\n" "$red" "$x" "$config_file" "$x" >&2
            return 1
        else
            # Local discovery - just warn and continue with defaults
            printf "%sNo configuration file found (%s), using built-in defaults%s\n" "$yellow" "$config_file" "$x" >&2
            return 2  # Special return code for "defaults used"
        fi
    fi
}

