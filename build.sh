# Quarantine a file with metadata preservation
quarantine_file() {
    local source_file="$1"
    local quarantine_reason="${2:-conflict}"
    
    if [[ ! -f "$source_file" ]]; then
        printf "%sWARN:%s Source file not found: %s\n" "$yellow" "$x" "$source_file" >&2
        return 1
    fi
    
    # Ensure quarantine directory exists
    create_quarantine_dir || return 1
    
    local quarantine_dir="$PARTS_DIR/$QUARANTINE_DIR"
    local basename_file=$(basename "$source_file")
    local quarantine_path="$quarantine_dir/$basename_file"
    
    # Handle naming conflicts in quarantine
    local counter=1
    local original_quarantine_path="$quarantine_path"
    while [[ -f "$quarantine_path" ]]; do
        local name_part="${basename_file%.*}"
        local ext_part="${basename_file##*.}"
        if [[ "$name_part" == "$ext_part" ]]; then
            # No extension
            quarantine_path="$quarantine_dir/${basename_file}.${counter}"
        else
            quarantine_path="$quarantine_dir/${name_part}.${counter}.${ext_part}"
        fi
        ((counter++))
    done
    
    # Move file to quarantine
    printf "  %s🏥%s Quarantining: %s → %s\n" "$yellow" "$x" "$basename_file" "$(basename "$quarantine_path")"
    mv "$source_file" "$quarantine_path" || {
        printf "%sERROR:%s Failed to quarantine file: %s\n" "$red" "$x" "$source_file" >&2
        return 1
    }
    
    # Create metadata file
    track_quarantine "$quarantine_path" "$source_file" "$quarantine_reason"
    return $?
}

# Create metadata tracking for quarantined files
track_quarantine() {
    local quarantine_path="$1"
    local original_path="$2" 
    local reason="$3"
    
    local metadata_file="${quarantine_path}.meta"
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    
    # Get file stats before they're lost
    local file_stats=""
    if [[ -f "$quarantine_path" ]]; then
        file_stats=$(stat -c "mode=%a size=%s mtime=%Y" "$quarantine_path" 2>/dev/null || echo "stats_unavailable")
    fi
    
    # Write metadata
    cat > "$metadata_file" << EOF
# Quarantine metadata
quarantined_at=$timestamp
original_path=$original_path
reason=$reason
quarantine_path=$quarantine_path
file_stats=$file_stats
EOF
    
    return 0
}

# List all quarantined files
list_quarantined_files() {
    local quarantine_dir="$PARTS_DIR/$QUARANTINE_DIR"
    
    if [[ ! -d "$quarantine_dir" ]]; then
        printf "%sNo quarantine directory found%s\n" "$yellow" "$x"
        return 0
    fi
    
    printf "%sQuarantined files in %s:%s\n" "$blue" "$quarantine_dir" "$x"
    
    local count=0
    for file in "$quarantine_dir"/*; do
        [[ -f "$file" ]] || continue
        [[ "$file" == *.meta ]] && continue  # Skip metadata files
        
        local basename_file=$(basename "$file")
        local metadata_file="${file}.meta"
        
        printf "  %s%s%s" "$green" "$basename_file" "$x"
        
        # Show metadata if available
        if [[ -f "$metadata_file" ]]; then
            local quarantined_at=$(grep "^quarantined_at=" "$metadata_file" | cut -d'=' -f2-)
            local reason=$(grep "^reason=" "$metadata_file" | cut -d'=' -f2-)
            local original_path=$(grep "^original_path=" "$metadata_file" | cut -d'=' -f2-)
            printf " (%s, %s, from %s)" "$quarantined_at" "$reason" "$(basename "$original_path")"
        fi
        printf "\n"
        ((count++))
    done
    
    if [[ $count -eq 0 ]]; then
        printf "  %sNo files in quarantine%s\n" "$yellow" "$x"
    else
        printf "\n%sTotal quarantined: %d files%s\n" "$blue" "$count" "$x"
    fi
    
    return 0
}

# Restore a specific file from quarantine
restore_quarantined_file() {
    local filename="$1"
    local quarantine_dir="$PARTS_DIR/$QUARANTINE_DIR"
    local quarantine_path="$quarantine_dir/$filename"
    local metadata_file="${quarantine_path}.meta"
    
    if [[ ! -f "$quarantine_path" ]]; then
        printf "%sERROR:%s Quarantined file not found: %s\n" "$red" "$x" "$filename" >&2
        return 1
    fi
    
    # Get original path from metadata
    local restore_path="$PARTS_DIR/$filename"  # Default restoration path
    if [[ -f "$metadata_file" ]]; then
        local original_path=$(grep "^original_path=" "$metadata_file" | cut -d'=' -f2-)
        if [[ -n "$original_path" ]]; then
            restore_path="$original_path"
        fi
    fi
    
    # Check if restore would conflict
    if [[ -f "$restore_path" ]]; then
        printf "%sWARN:%s Target file already exists: %s\n" "$yellow" "$x" "$restore_path" >&2
        printf "Restore would overwrite existing file. Continue? (y/N): "
        read -r confirm
        if [[ "$confirm" != [yY] ]]; then
            printf "Restore cancelled.\n"
            return 1
        fi
    fi
    
    # Restore the file
    printf "%s↶%s Restoring: %s → %s\n" "$green" "$x" "$filename" "$(basename "$restore_path")"
    mv "$quarantine_path" "$restore_path" || {
        printf "%sERROR:%s Failed to restore file\n" "$red" "$x" >&2
        return 1
    }
    
    # Remove metadata file
    rm -f "$metadata_file"
    
    printf "%s✓ Restored successfully%s\n" "$green" "$x"
    return 0
}

# Restore all quarantined files
restore_all_quarantined_files() {
    local quarantine_dir="$PARTS_DIR/$QUARANTINE_DIR"
    
    if [[ ! -d "$quarantine_dir" ]]; then
        printf "%sNo quarantine directory found%s\n" "$yellow" "$x"
        return 0
    fi
    
    printf "%sRestoring all quarantined files...%s\n" "$blue" "$x"
    
    local restored_count=0
    local failed_count=0
    
    for file in "$quarantine_dir"/*; do
        [[ -f "$file" ]] || continue
        [[ "$file" == *.meta ]] && continue  # Skip metadata files
        
        local basename_file=$(basename "$file")
        if restore_quarantined_file "$basename_file"; then
            ((restored_count++))
        else
            ((failed_count++))
        fi
    done
    
    printf "\n%sRestore complete:%s %d restored, %d failed\n" "$green" "$x" "$restored_count" "$failed_count"
    return 0
}

# Purge quarantined files permanently
purge_quarantined_files() {
    local quarantine_dir="$PARTS_DIR/$QUARANTINE_DIR"
    
    if [[ ! -d "$quarantine_dir" ]]; then
        printf "%sNo quarantine directory found%s\n" "$yellow" "$x"
        return 0
    fi
    
    # Count files first
    local file_count=0
    for file in "$quarantine_dir"/*; do
        [[ -f "$file" ]] || continue
        [[ "$file" == *.meta ]] && continue
        ((file_count++))
    done
    
    if [[ $file_count -eq 0 ]]; then
        printf "%sNo files to purge%s\n" "$yellow" "$x"
        return 0
    fi
    
    printf "%sWARN:%s About to permanently delete %d quarantined files\n" "$red" "$x" "$file_count" >&2
    printf "This action cannot be undone. Continue? (y/N): "
    read -r confirm
    
    if [[ "$confirm" != [yY] ]]; then
        printf "Purge cancelled.\n"
        return 0
    fi
    
    printf "%sDeleting quarantined files...%s\n" "$red" "$x"
    
    local deleted_count=0
    for file in "$quarantine_dir"/*; do
        [[ -f "$file" ]] || continue
        
        local basename_file=$(basename "$file")
        printf "  %s🗑%s %s\n" "$red" "$x" "$basename_file"
        rm -f "$file"
        ((deleted_count++))
    done
    
    # Remove quarantine directory if empty
    if [[ -d "$quarantine_dir" ]]; then
        rmdir "$quarantine_dir" 2>/dev/null && {
            printf "%sQuarantine directory removed (was empty)%s\n" "$blue" "$x"
        }
    fi
    
    printf "\n%s✓ Purged %d files permanently%s\n" "$green" "$x" "$deleted_count"
    return 0
}

