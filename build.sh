# Extracts and displays version information from script and configuration
extract_script_version() {
    local script_path="${1:-$0}"  # Default to current script
    
    # Try to extract version from script header comment
    local script_version=""
    if [[ -f "$script_path" ]]; then
        script_version=$(grep -E '^#[[:space:]]*version:[[:space:]]*' "$script_path" | head -n1 | sed 's/^#[[:space:]]*version:[[:space:]]*//' | xargs)
    fi
    
    echo "$script_version"
}

# Version comparison utilities (for future upgrade mechanisms)
version_compare() {
    local version1="$1"
    local version2="$2"
    
    # Simple semantic version comparison
    # Returns: 0 if equal, 1 if version1 > version2, -1 if version1 < version2
    
    # Split versions into components
    IFS='.' read -ra V1 <<< "${version1%%-*}"  # Remove any suffixes like -dev
    IFS='.' read -ra V2 <<< "${version2%%-*}"
    
    # Pad arrays to same length
    local max_len=$((${#V1[@]} > ${#V2[@]} ? ${#V1[@]} : ${#V2[@]}))
    
    for ((i=0; i<max_len; i++)); do
        local v1_part=${V1[i]:-0}
        local v2_part=${V2[i]:-0}
        
        # Compare numeric parts
        if [[ $v1_part -gt $v2_part ]]; then
            return 1
        elif [[ $v1_part -lt $v2_part ]]; then
            return -1
        fi
    done
    
    return 0
}

# Main version information display
do_version() {
    local format="${1:-default}"
    
    # Extract version from script header
    local script_version
    script_version=$(extract_script_version "$0")
    
    # Get version from configuration (already loaded)
    local config_version="$PROJECT_VERSION"
    
    case "$format" in
        (--short|-s)
            # Short format: just the version number
            if [[ -n "$script_version" ]]; then
                echo "$script_version"
            elif [[ -n "$config_version" ]]; then
                echo "$config_version"
            else
                echo "unknown"
            fi
            ;;
        (--script-only)
            # Show only script version
            if [[ -n "$script_version" ]]; then
                echo "$script_version"
            else
                echo "unknown"
                return 1
            fi
            ;;
        (--config-only)
            # Show only config version
            if [[ -n "$config_version" ]]; then
                echo "$config_version"
            else
                echo "unknown"
                return 1
            fi
            ;;
        (*)
            # Default detailed format
            printf "%s%s Version Information%s\n" "$blue" "$PROJECT_NAME" "$x"
            printf "════════════════════════════════\n"
            
            # Script version
            if [[ -n "$script_version" ]]; then
                printf "%sScript Version:%s %s\n" "$green" "$x" "$script_version"
            else
                printf "%sScript Version:%s %sunknown%s\n" "$yellow" "$x" "$yellow" "$x"
