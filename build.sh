# Warning with consistent formatting
warn_user() {
    local message="$1"
    printf "%sWARN:%s %s\n" "$yellow" "$x" "$message" >&2
}

# Success message formatting
success_msg() {
    local message="$1"
    printf "%s✓%s %s\n" "$green" "$x" "$message"
}

# Operation status tracking
declare -a _cleanup_files=()
declare -a _cleanup_dirs=()
declare _operation_started=false

# Register file for cleanup on failure
register_cleanup_file() {
    local file="$1"
    _cleanup_files+=("$file")
}

# Register directory for cleanup on failure
register_cleanup_dir() {
    local dir="$1"
    _cleanup_dirs+=("$dir")
}

# Mark operation as started (enables cleanup)
mark_operation_start() {
    _operation_started=true
}

# Clean up partial operation on failure
cleanup_on_failure() {
    local operation="${1:-operation}"
    
    if [[ "$_operation_started" != true ]]; then
        return 0
    fi
    
    warn_user "Cleaning up failed $operation..."
    
    # Remove temporary files
    for file in "${_cleanup_files[@]}"; do
        if [[ -f "$file" ]]; then
            printf "  Removing: %s\n" "$file"
            rm -f "$file" 2>/dev/null || warn_user "Failed to cleanup: $file"
        fi
    done
    
    # Remove temporary directories (only if empty)
    for dir in "${_cleanup_dirs[@]}"; do
        if [[ -d "$dir" ]]; then
            printf "  Removing: %s\n" "$dir" 
            rmdir "$dir" 2>/dev/null || warn_user "Failed to cleanup: $dir (may not be empty)"
        fi
    done
    
    # Reset cleanup state
    _cleanup_files=()
    _cleanup_dirs=()
    _operation_started=false
    
    printf "%s✓%s Cleanup complete\n" "$green" "$x"
}

# Wrapper for critical operations with automatic cleanup
safe_operation() {
    local operation_name="$1"
    local operation_func="$2"
    shift 2  # Remove first two args, pass rest to function
    
    printf "%sStarting %s operation...%s\n" "$blue" "$operation_name" "$x"
    mark_operation_start
    
    # Set up trap for cleanup on exit/error
    trap "cleanup_on_failure '$operation_name'" ERR EXIT
    
    # Execute the operation
    if "$operation_func" "$@"; then
        # Operation succeeded - clear trap and reset state
        trap - ERR EXIT
        _operation_started=false
        _cleanup_files=()
        _cleanup_dirs=()
        success_msg "$operation_name operation completed successfully"
        return 0
    else
        # Operation failed - cleanup will happen via trap
        return 1
    fi
}

