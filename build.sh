# Parse global options into opt_* variables
# This function handles all global flags and preserves remaining arguments
options() {
    local args=("$@")
    local i
    
    for ((i=0; i<${#args[@]}; i++)); do
        case "${args[i]}" in
            (-q|--quiet)
                opt_quiet=true
                ;;
            (-v|--verbose)
                opt_verbose=true
                ;;
            (--version)
                _version_requested=true
                ;;
            (-o|--output)
                if [[ $((i+1)) -lt ${#args[@]} ]]; then
                    opt_output="${args[$((i+1))]}"
                    ((i++))
                else
                    printf "%sERROR:%s --output requires an argument\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (-p|--parts)
                if [[ $((i+1)) -lt ${#args[@]} ]]; then
                    opt_parts="${args[$((i+1))]}"
                    ((i++))
                else
                    printf "%sERROR:%s --parts requires an argument\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (-m|--map)
                if [[ $((i+1)) -lt ${#args[@]} ]]; then
                    opt_map="${args[$((i+1))]}"
                    ((i++))
                else
                    printf "%sERROR:%s --map requires an argument\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (--conf)
                if [[ $((i+1)) -lt ${#args[@]} ]]; then
                    opt_conf="${args[$((i+1))]}"
                    ((i++))
                else
                    printf "%sERROR:%s --conf requires an argument\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (--conf=*)
                opt_conf="${args[i]#*=}"
                if [[ -z "$opt_conf" ]]; then
                    printf "%sERROR:%s --conf= requires a value\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            # Legacy flag support for backward compatibility
            (-i)  # Insert mode
                if [[ $((i+2)) -lt ${#args[@]} ]]; then
                    _compat_mode="insert"
                    _compat_args=("${args[$((i+1))]}" "${args[$((i+2))]}")
                    ((i+=2))
                else
                    printf "%sERROR:%s -i requires MODULE and POSITION arguments\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (-s)  # Swap mode
                if [[ $((i+2)) -lt ${#args[@]} ]]; then
                    _compat_mode="swap"
                    _compat_args=("${args[$((i+1))]}" "${args[$((i+2))]}")
                    ((i+=2))
                else
                    printf "%sERROR:%s -s requires POS1 and POS2 arguments\n" "$red" "$x" >&2
                    return 1
                fi
                ;;
            (-r)  # Remap mode
                _compat_mode="remap"
                ;;
            (-l)  # List mode
                _compat_mode="list"
                ;;
            (-c)  # Clean mode
                opt_clean=true
                ;;
            (-h|--help)
                _help_requested=true
                ;;
            (-*)
                printf "%sERROR:%s Unknown option: %s\n" "$red" "$x" "${args[i]}" >&2
                return 1
                ;;
            (*)
                # Non-option argument - preserve for subcommand
                break
                ;;
        esac
    done
    
    # Export remaining arguments for dispatch
    _remaining_args=("${args[@]:i}")
    return 0
}

