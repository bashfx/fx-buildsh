################################################################################
#
#  main - BashFX3 Main Orchestrator
#
################################################################################
# Primary entry point - manages script lifecycle
# Follows BashFX3 pattern: load config → options → dispatch → execution
main() {
    # Initialize global state variables
    local ret=0
    
    # First pass: Parse options to extract --conf option without full processing
    # Initialize minimal option variables for configuration discovery
    opt_conf=""
    opt_quiet=""
    opt_verbose=""
    opt_output=""
    opt_parts=""
    opt_map=""
    
    # Parse command-line options to discover configuration file location
    if ! options "$@"; then
        usage >&2
        return 1
    fi
    
    # Load configuration using discovered config file location
    if ! load_configuration; then
        local config_ret=$?
        # Exit on hard errors (missing explicitly specified config files)
        if [[ $config_ret -eq 1 ]]; then
            return 1
        fi
        # Continue with defaults for soft errors (no local build.conf found)
    fi
    
    # Initialize option variables from configuration
    # Only set if not already set by command-line options
    [[ -z "$opt_quiet" ]] && opt_quiet="$DEFAULT_QUIET"
    [[ -z "$opt_verbose" ]] && opt_verbose="$DEFAULT_VERBOSE"
    [[ -z "$opt_output" ]] && opt_output="$OUTPUT_FILE"
    [[ -z "$opt_parts" ]] && opt_parts="$PARTS_DIR"
    [[ -z "$opt_map" ]] && opt_map="$BUILD_MAP"
    
    # Set up environment from parsed options
    [[ "$opt_verbose" == true ]] && set -x
    
    # Handle clean option if specified
    if [[ "${opt_clean:-false}" == true ]] && [[ -f "$opt_output" ]]; then
        [[ "$opt_quiet" != true ]] && printf "%sCleaning:%s Removing %s\n" "$yellow" "$x" "$opt_output"
        rm -f "$opt_output"
    fi
    
    # Update global configuration from options
    PARTS_DIR="$opt_parts"
    OUTPUT_FILE="$opt_output"
    BUILD_MAP="$opt_map"
    
    # Dispatch to appropriate subcommand
    dispatch "${_remaining_args[@]}"
    ret=$?
    
    return $ret
}

