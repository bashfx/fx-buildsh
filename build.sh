    fi
    
    printf "\n%sModules found:%s\n" "$blue" "$x"
    
    # List modules
    local count=0
    if [[ "$use_map" == true ]] && [[ ${#build_map_targets[@]} -gt 0 ]]; then
        # List from build map
        for num in $(printf '%s\n' "${!build_map_targets[@]}" | sort -n); do
            local target="${build_map_targets[$num]}"
            if [[ -f "$PARTS_DIR/$target" ]]; then
                printf "  %s%02d%s: %s%s%s" "$green" "$((10#$num))" "$x" "$green" "$target" "$x"
                local lines=$(wc -l < "$PARTS_DIR/$target")
