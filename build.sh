                break
                ;;
        esac
    done
    
    # Enhanced namespace for environment-specific deployments
    if [[ -n "$environment" ]]; then
        namespace="${namespace}-${environment}"
    fi
    
    # Multi-version support adds version to namespace
    if [[ "$multi_version" == "true" ]]; then
        local version_slug=$(echo "$PROJECT_VERSION" | tr '.' '-' | tr -d '+')
        namespace="${namespace}-${version_slug}"
    fi
    
    # Use custom target directory if specified
    local xdg_dirs
    if [[ -n "$target_dir" ]]; then
        # Custom deployment paths
        local abs_target=$(readlink -f "$target_dir")
        echo "data_dir=$abs_target/data"
        echo "lib_dir=$abs_target/lib"
        echo "bin_dir=$abs_target/bin"
        echo "registry=$abs_target/deploy.registry"
        xdg_dirs=$(cat << EOF
data_dir=$abs_target/data
lib_dir=$abs_target/lib
bin_dir=$abs_target/bin
registry=$abs_target/deploy.registry
EOF
)
    else
        # Standard XDG paths
        xdg_dirs=$(get_xdg_directories "$scope")
    fi
    
    local data_dir=$(echo "$xdg_dirs" | grep "^data_dir=" | cut -d= -f2-)
    local lib_dir=$(echo "$xdg_dirs" | grep "^lib_dir=" | cut -d= -f2-)
    local bin_dir=$(echo "$xdg_dirs" | grep "^bin_dir=" | cut -d= -f2-)
    local registry=$(echo "$xdg_dirs" | grep "^registry=" | cut -d= -f2-)
    
    # Deployment-specific subdirectories
    lib_dir="$lib_dir/$org/$namespace"
    
    printf "%sDeploying %s %s%s\n" "$blue" "$PROJECT_NAME" "$PROJECT_VERSION" "$x"
    printf "Deployment configuration:\n"
    printf "  %sScope:%s %s\n" "$green" "$x" "$scope"
    printf "  %sOrganization:%s %s\n" "$green" "$x" "$org"
    printf "  %sNamespace:%s %s\n" "$green" "$x" "$namespace"
    [[ -n "$environment" ]] && printf "  %sEnvironment:%s %s\n" "$green" "$x" "$environment"
    [[ "$multi_version" == "true" ]] && printf "  %sMulti-version:%s enabled\n" "$green" "$x"
    printf "  %sTarget directories:%s\n" "$green" "$x"
    printf "    - Lib: %s\n" "$lib_dir"
    printf "    - Bin: %s\n" "$bin_dir"
    printf "    - Registry: %s\n" "$registry"
    
    if [[ "$dry_run" == "true" ]]; then
        printf "\n%s[DRY RUN] Would perform deployment with the above configuration%s\n" "$yellow" "$x"
        return 0
    fi
    
    # Validate environment
    if [[ "$scope" == "system" ]]; then
        if [[ $EUID -ne 0 ]]; then
            printf "%sERROR:%s System deployment requires root privileges\n" "$red" "$x" >&2
            printf "Try: sudo %s deploy --global\n" "$(basename "$0")" >&2
            return 1
        fi
    fi
    
    # Create directory structure
    for dir in "$data_dir" "$lib_dir" "$bin_dir" "$(dirname "$registry")"; do
        if ! mkdir -p "$dir" 2>/dev/null; then
            printf "%sERROR:%s Cannot create directory: %s\n" "$red" "$x" "$dir" >&2
            return 1
        fi
    done
    
    # Generate deployment ID
    local deploy_id="${org}-${namespace}"
    
    # Enhanced deployment conflict resolution
    if check_installation_exists "$registry" "$deploy_id" && [[ "$force_install" != "true" ]]; then
        printf "%sWARN:%s Deployment '%s' already exists\n" "$yellow" "$x" "$deploy_id"
        local existing_info
        existing_info=$(get_installation_info "$registry" "$deploy_id")
        local existing_version=$(echo "$existing_info" | cut -d: -f4)
        printf "Existing version: %s, New version: %s\n" "$existing_version" "$PROJECT_VERSION"
        
        # Intelligent version comparison and upgrade logic
        local version_comparison=$(version_compare "$existing_version" "$PROJECT_VERSION")
        
        if [[ "$auto_upgrade" == "true" ]] && [[ "$version_comparison" == "older" ]]; then
            printf "%sAuto-upgrade enabled: upgrading from %s to %s%s\n" "$blue" "$existing_version" "$PROJECT_VERSION" "$x"
            if [[ "$backup_existing" == "true" ]]; then
                printf "%sCreating backup of existing deployment...%s\n" "$green" "$x"
                # Create backup with timestamp
                local backup_timestamp=$(date +%Y%m%d_%H%M%S)
                local backup_suffix="${backup_timestamp}_v${existing_version//[^a-zA-Z0-9._-]/_}"
                # Implementation of backup logic would go here
            fi
        elif [[ "$multi_version" == "true" ]]; then
            printf "Multi-version deployment allows parallel versions\n"
        elif [[ "$version_comparison" == "newer" ]]; then
            printf "%sWARN:%s Trying to install older version (%s) over newer (%s)\n" "$yellow" "$x" "$PROJECT_VERSION" "$existing_version"
            printf "Use --force to downgrade, --multi-version for parallel deployment\n"
            return 1
        elif [[ "$version_comparison" == "same" ]]; then
            printf "%sINFO:%s Same version already deployed\n" "$blue" "$x"
            printf "Use --force to reinstall, --multi-version for separate deployment\n"
            return 0
        else
            printf "Use --force to overwrite, --multi-version for parallel deployment\n"
            printf "Use --auto-upgrade to automatically upgrade when newer version is available\n"
            return 1
        fi
    fi
    
    # Apply deployment template if specified
    if [[ -n "$deployment_template" ]]; then
        printf "%sApplying deployment template: %s%s\n" "$blue" "$deployment_template" "$x"
        if ! apply_deployment_template "$deployment_template" "$org" "$namespace" "$environment"; then
            printf "%sERROR:%s Failed to apply deployment template\n" "$red" "$x" >&2
            return 1
        fi
    fi
    
    printf "\n%sDeploying files...%s\n" "$yellow" "$x"
    
    # Build first if output doesn't exist
    local output_file="$OUTPUT_FILE"
    if [[ ! -f "$output_file" ]]; then
        printf "%sBuild output not found, building first...%s\n" "$blue" "$x"
        if ! do_build; then
            printf "%sERROR:%s Build failed, cannot continue with deployment\n" "$red" "$x" >&2
            return 1
        fi
    fi
    
    # Deploy main script
    local script_deploy_path="$lib_dir/$(basename "$output_file")"
    printf "%s  Deploying script: %s%s\n" "$green" "$script_deploy_path" "$x"
    cp "$output_file" "$script_deploy_path"
    chmod 755 "$script_deploy_path"
    
    # Deploy configuration if enabled
    if [[ "$config_deployment" == "true" ]] && [[ -f "build.conf" ]]; then
        local config_deploy_path="$lib_dir/build.conf"
        printf "%s  Deploying config: %s%s\n" "$green" "$config_deploy_path" "$x"
        cp "build.conf" "$config_deploy_path"
        chmod 644 "$config_deploy_path"
        
        # Environment-specific config if it exists
        if [[ -n "$environment" ]] && [[ -f "build.${environment}.conf" ]]; then
            local env_config_path="$lib_dir/build.${environment}.conf"
            printf "%s  Deploying environment config: %s%s\n" "$green" "$env_config_path" "$x"
            cp "build.${environment}.conf" "$env_config_path"
            chmod 644 "$env_config_path"
        fi
    fi
    
    # Create executable link or wrapper
    local bin_link="$bin_dir/$deploy_id"
    if [[ "$create_wrapper" == "true" ]]; then
        printf "%s  Creating wrapper script: %s%s\n" "$green" "$bin_link" "$x"
        cat > "$bin_link" << EOF
#!/bin/bash
# Deployment wrapper for $PROJECT_NAME $PROJECT_VERSION
# Generated by fx-buildsh deploy command
exec "$script_deploy_path" "\$@"
EOF
        chmod 755 "$bin_link"
    else
        create_safe_symlink "$script_deploy_path" "$bin_link"
    fi
    
    # Update deployment registry
    local timestamp=$(date +%s)
    local deploy_metadata="${org}:${namespace}:${environment:-none}:${multi_version}"
    create_installation_record "$registry" "$deploy_id" "$script_deploy_path" "$(readlink -f "$output_file")" "$PROJECT_VERSION" "$timestamp"
    
    # Add deployment metadata to registry
    printf "%s\n" "$deploy_metadata" >> "${registry}.meta" 2>/dev/null || true
    
    printf "\n%s✓ Deployment complete!%s\n" "$green" "$x"
    printf "%sDeployed as:%s %s\n" "$blue" "$x" "$deploy_id"
    printf "%sExecutable:%s %s\n" "$blue" "$x" "$bin_link"
    
    # Show deployment summary
    printf "\n%sDeployment Summary:%s\n" "$blue" "$x"
    printf "  %sName:%s %s\n" "$green" "$x" "$PROJECT_NAME"
    printf "  %sVersion:%s %s\n" "$green" "$x" "$PROJECT_VERSION"
    printf "  %sDeployment ID:%s %s\n" "$green" "$x" "$deploy_id"
    [[ -n "$environment" ]] && printf "  %sEnvironment:%s %s\n" "$green" "$x" "$environment"
    [[ "$multi_version" == "true" ]] && printf "  %sVersioning:%s Multi-version enabled\n" "$green" "$x"
    
    # PATH advice for custom targets
    if [[ -n "$target_dir" ]] || [[ "$scope" == "user" ]]; then
        printf "\n%sNote:%s Ensure %s is in your PATH:\n" "$yellow" "$x" "$bin_dir"
        printf "  export PATH=\"%s:\$PATH\"\n" "$bin_dir"
    fi
    
    return 0
}

# Integration testing for cohesive experience
do_test() {
    local test_scope="${1:-basic}"
    local verbose=false
    
    # Parse options
    while [[ $# -gt 0 ]]; do
        case "$1" in
            (--verbose|-v)
                verbose=true
                shift
                ;;
            (--scope)
                test_scope="$2"
                shift 2
                ;;
            (--scope=*)
                test_scope="${1#*=}"
                shift
                ;;
            (-*)
                printf "%sERROR:%s Unknown test option: %s\n" "$red" "$x" "$1" >&2
                return 1
                ;;
            (*)
                test_scope="$1"
                shift
                ;;
        esac
    done
    
    printf "%s%s Integration Testing%s\n" "$blue" "$PROJECT_NAME" "$x"
    printf "═══════════════════════════════════════\n\n"
    
    case "$test_scope" in
        (basic|core)
            test_core_functionality "$verbose"
