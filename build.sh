}

# Deployment template application
apply_deployment_template() {
    local template="$1"
    local org="$2"
    local namespace="$3"
    local environment="${4:-}"
    
    local template_file=""
    
    # Check for template in multiple locations
    if [[ -f "$template" ]]; then
        template_file="$template"
    elif [[ -f "templates/${template}.template" ]]; then
        template_file="templates/${template}.template"
    elif [[ -f ".deploy/${template}.template" ]]; then
        template_file=".deploy/${template}.template"
    else
        printf "%sERROR:%s Deployment template not found: %s\n" "$red" "$x" "$template" >&2
        printf "Searched locations:\n" >&2
        printf "  - %s\n" "$template" >&2
        printf "  - templates/${template}.template\n" >&2
        printf "  - .deploy/${template}.template\n" >&2
        return 1
    fi
    
    printf "%sProcessing template: %s%s\n" "$green" "$template_file" "$x"
    
    # Create deployment configuration from template
    local temp_deploy_conf=$(mktemp)
    
    # Process template with variable substitution
    while IFS= read -r line || [[ -n "$line" ]]; do
        # Skip comments and empty lines
        [[ "$line" =~ ^[[:space:]]*# ]] && continue
        [[ -z "${line// }" ]] && continue
        
        # Variable substitution
        line="${line//\$ORG/$org}"
        line="${line//\$NAMESPACE/$namespace}"
        line="${line//\$ENVIRONMENT/$environment}"
        line="${line//\$PROJECT_NAME/$PROJECT_NAME}"
        line="${line//\$PROJECT_VERSION/$PROJECT_VERSION}"
        
        echo "$line" >> "$temp_deploy_conf"
    done < "$template_file"
    
    # Apply template configurations
    if [[ -s "$temp_deploy_conf" ]]; then
        printf "%sApplying template configurations...%s\n" "$green" "$x"
        
        # Source the processed template to set variables
        # This allows templates to override deployment behavior
        source "$temp_deploy_conf"
        
        printf "%sTemplate applied successfully%s\n" "$green" "$x"
    fi
    
    rm -f "$temp_deploy_conf"
    return 0
}

# Installation registry management
create_installation_record() {
    local registry_file="$1"
    local install_id="$2"
    local install_path="$3"
    local script_path="$4"
    local version="$5"
    local timestamp="$6"
    
    # Ensure registry directory exists
    mkdir -p "$(dirname "$registry_file")"
    
    # Create or update registry entry
    local temp_registry=$(mktemp)
    
    # Copy existing entries (excluding same install_id)
    if [[ -f "$registry_file" ]]; then
        grep -v "^$install_id:" "$registry_file" > "$temp_registry" 2>/dev/null || true
    fi
    
    # Add new entry
    printf "%s:%s:%s:%s:%s:%s\n" "$install_id" "$install_path" "$script_path" "$version" "$timestamp" "$PROJECT_NAME" >> "$temp_registry"
    
    # Replace registry atomically
    mv "$temp_registry" "$registry_file"
    chmod 644 "$registry_file"
}

# Remove installation record
remove_installation_record() {
    local registry_file="$1"
    local install_id="$2"
    
    if [[ -f "$registry_file" ]]; then
        local temp_registry=$(mktemp)
        grep -v "^$install_id:" "$registry_file" > "$temp_registry" 2>/dev/null || true
        mv "$temp_registry" "$registry_file"
    fi
}

# Check if installation exists
check_installation_exists() {
    local registry_file="$1"
    local install_id="$2"
    
    [[ -f "$registry_file" ]] && grep -q "^$install_id:" "$registry_file"
}

# Get installation info
get_installation_info() {
    local registry_file="$1"
    local install_id="$2"
    
    if [[ -f "$registry_file" ]]; then
        grep "^$install_id:" "$registry_file" | head -n1
    fi
}

# List all installations
list_installations() {
    local registry_file="$1"
    
    if [[ -f "$registry_file" ]]; then
        printf "%sInstalled packages:%s\n" "$blue" "$x"
        printf "%-20s %-12s %-16s %s\n" "Package" "Version" "Installed" "Location"
        printf "%s\n" "────────────────────────────────────────────────────────────────────"
        
        while IFS=':' read -r install_id install_path script_path version timestamp project_name; do
            local install_date=$(date -d "@$timestamp" "+%Y-%m-%d %H:%M" 2>/dev/null || echo "$timestamp")
            printf "%-20s %-12s %-16s %s\n" "$install_id" "$version" "$install_date" "$install_path"
        done < "$registry_file"
    else
        printf "%sNo installations found%s\n" "$yellow" "$x"
    fi
}

# Create safe symlink with backup handling
create_safe_symlink() {
    local target="$1"
    local link_path="$2"
    local backup_existing="${3:-true}"
    
    # Ensure target directory exists
    mkdir -p "$(dirname "$link_path")"
    
    # Handle existing file/link
    if [[ -e "$link_path" ]] || [[ -L "$link_path" ]]; then
        if [[ "$backup_existing" == "true" ]]; then
            local backup_path="${link_path}.bak.$(date +%Y%m%d_%H%M%S)"
            printf "%s  Backing up existing: %s → %s%s\n" "$yellow" "$(basename "$link_path")" "$(basename "$backup_path")" "$x"
            mv "$link_path" "$backup_path"
        else
            printf "%s  Removing existing: %s%s\n" "$yellow" "$(basename "$link_path")" "$x"
            rm -f "$link_path"
        fi
    fi
    
    # Create symlink
    ln -sf "$target" "$link_path"
    printf "%s  Created symlink: %s → %s%s\n" "$green" "$(basename "$link_path")" "$target" "$x"
}

# Validate installation environment
validate_installation_environment() {
    local scope="$1"
    local xdg_dirs="$2"
    
    # Parse XDG directories
    local data_dir=$(echo "$xdg_dirs" | grep "^data_dir=" | cut -d= -f2-)
    local lib_dir=$(echo "$xdg_dirs" | grep "^lib_dir=" | cut -d= -f2-)
    local bin_dir=$(echo "$xdg_dirs" | grep "^bin_dir=" | cut -d= -f2-)
    
    # Check write permissions
    if [[ "$scope" == "system" ]]; then
        if [[ $EUID -ne 0 ]]; then
            printf "%sERROR:%s System installation requires root privileges\n" "$red" "$x" >&2
            printf "Try: sudo %s install --global\n" "$(basename "$0")" >&2
            return 1
        fi
    fi
    
    # Test directory creation capability
    for dir in "$data_dir" "$lib_dir" "$bin_dir"; do
        if ! mkdir -p "$dir" 2>/dev/null; then
            printf "%sERROR:%s Cannot create directory: %s\n" "$red" "$x" "$dir" >&2
            return 1
        fi
    done
    
    return 0
}

# Main installation function
do_install() {
    local scope="user"
    local force_install=false
    local dry_run=false
    local org="${DEFAULT_ORG:-fx}"
    local namespace="${DEFAULT_NAMESPACE:-buildsh}"
    
    # Parse options
    while [[ $# -gt 0 ]]; do
        case "$1" in
            (--global|--system)
                scope="system"
                shift
                ;;
            (--user)
                scope="user"
                shift
                ;;
            (--force|-f)
                force_install=true
                shift
                ;;
            (--dry-run|-n)
                dry_run=true
                shift
                ;;
            (--org)
                org="$2"
                shift 2
                ;;
            (--namespace)
                namespace="$2"
                shift 2
                ;;
            (-*)
                printf "%sERROR:%s Unknown install option: %s\n" "$red" "$x" "$1" >&2
                return 1
                ;;
            (*)
                break
                ;;
        esac
    done
    
    # Get XDG directories
    local xdg_dirs
    xdg_dirs=$(get_xdg_directories "$scope")
    local data_dir=$(echo "$xdg_dirs" | grep "^data_dir=" | cut -d= -f2-)
    local lib_dir=$(echo "$xdg_dirs" | grep "^lib_dir=" | cut -d= -f2-)
    local bin_dir=$(echo "$xdg_dirs" | grep "^bin_dir=" | cut -d= -f2-)
    local registry=$(echo "$xdg_dirs" | grep "^registry=" | cut -d= -f2-)
    
    printf "%sInstalling %s %s (%s installation)%s\n" "$blue" "$PROJECT_NAME" "$PROJECT_VERSION" "$scope" "$x"
    printf "Target directories:\n"
    printf "  %sLib:%s %s\n" "$green" "$x" "$lib_dir"
    printf "  %sBin:%s %s\n" "$green" "$x" "$bin_dir"
    printf "  %sRegistry:%s %s\n" "$green" "$x" "$registry"
    
    if [[ "$dry_run" == "true" ]]; then
        printf "\n%s[DRY RUN] Would perform the following actions:%s\n" "$yellow" "$x"
        return 0
    fi
    
    # Validate environment
    if ! validate_installation_environment "$scope" "$xdg_dirs"; then
        return 1
    fi
    
    # Generate installation ID
    local install_id="${org}-${namespace}"
    
    # Check for existing installation
    if check_installation_exists "$registry" "$install_id" && [[ "$force_install" != "true" ]]; then
        printf "%sWARN:%s Installation '%s' already exists\n" "$yellow" "$x" "$install_id"
        local existing_info
        existing_info=$(get_installation_info "$registry" "$install_id")
        local existing_version=$(echo "$existing_info" | cut -d: -f4)
        printf "Existing version: %s, New version: %s\n" "$existing_version" "$PROJECT_VERSION"
        printf "Use --force to overwrite, or uninstall first\n"
        return 1
    fi
    
    printf "\n%sInstalling files...%s\n" "$yellow" "$x"
    
    # Build first if output doesn't exist
    local output_file="$OUTPUT_FILE"
    if [[ ! -f "$output_file" ]]; then
        printf "%sBuild output not found, building first...%s\n" "$blue" "$x"
        if ! do_build; then
            printf "%sERROR:%s Build failed, cannot continue with installation\n" "$red" "$x" >&2
            return 1
        fi
    fi
    
    # Install main script to lib directory
    local script_install_path="$lib_dir/$(basename "$output_file")"
    printf "%s  Installing script: %s%s\n" "$green" "$script_install_path" "$x"
    cp "$output_file" "$script_install_path"
    chmod 755 "$script_install_path"
    
    # Install configuration if it exists
    if [[ -f "build.conf" ]]; then
        local config_install_path="$lib_dir/build.conf"
        printf "%s  Installing config: %s%s\n" "$green" "$config_install_path" "$x"
        cp "build.conf" "$config_install_path"
        chmod 644 "$config_install_path"
    fi
    
    # Create symlink in bin directory
    local bin_symlink="$bin_dir/$install_id"
    create_safe_symlink "$script_install_path" "$bin_symlink"
    
    # Update registry
    local timestamp=$(date +%s)
    create_installation_record "$registry" "$install_id" "$script_install_path" "$(readlink -f "$output_file")" "$PROJECT_VERSION" "$timestamp"
    
    printf "\n%s✓ Installation complete!%s\n" "$green" "$x"
    printf "%sInstalled as:%s %s\n" "$blue" "$x" "$install_id"
    printf "%sUsage:%s %s [options] [command]\n" "$blue" "$x" "$bin_symlink"
    
    # Add to PATH advice
    if [[ "$scope" == "user" ]]; then
        printf "\n%sNote:%s Ensure %s is in your PATH:\n" "$yellow" "$x" "$bin_dir"
        printf "  export PATH=\"%s:\$PATH\"\n" "$bin_dir"
    fi
    
    return 0
}

# Main uninstallation function  
do_uninstall() {
    local scope="user"
    local force_removal=false
    local org="${DEFAULT_ORG:-fx}"
    local namespace="${DEFAULT_NAMESPACE:-buildsh}"
    
    # Parse options
    while [[ $# -gt 0 ]]; do
        case "$1" in
            (--global|--system)
                scope="system"
                shift
                ;;
            (--user)
                scope="user"
                shift
                ;;
            (--force|-f)
                force_removal=true
                shift
                ;;
            (--org)
                org="$2"
                shift 2
                ;;
            (--org=*)
                org="${1#*=}"
                shift
                ;;
            (--namespace)
                namespace="$2"
                shift 2
                ;;
            (--namespace=*)
                namespace="${1#*=}"
                shift
                ;;
            (-*)
                printf "%sERROR:%s Unknown uninstall option: %s\n" "$red" "$x" "$1" >&2
                return 1
                ;;
            (*)
                break
                ;;
        esac
    done
    
    # Get XDG directories
    local xdg_dirs
    xdg_dirs=$(get_xdg_directories "$scope")
    local lib_dir=$(echo "$xdg_dirs" | grep "^lib_dir=" | cut -d= -f2-)
    local bin_dir=$(echo "$xdg_dirs" | grep "^bin_dir=" | cut -d= -f2-)
    local registry=$(echo "$xdg_dirs" | grep "^registry=" | cut -d= -f2-)
    
    # Generate installation ID
    local install_id="${org}-${namespace}"
    
    printf "%sUninstalling %s (%s)%s\n" "$blue" "$install_id" "$scope" "$x"
    
    # Check if installation exists
    if ! check_installation_exists "$registry" "$install_id"; then
        printf "%sERROR:%s Installation '%s' not found\n" "$red" "$x" "$install_id" >&2
        printf "Available installations:\n" >&2
        list_installations "$registry" >&2
        return 1
    fi
    
    # Get installation details
    local install_info
    install_info=$(get_installation_info "$registry" "$install_id")
    local install_path=$(echo "$install_info" | cut -d: -f2)
    local version=$(echo "$install_info" | cut -d: -f4)
    
    printf "Found installation: %s (version %s)\n" "$install_path" "$version"
    
    # Confirmation unless forced
    if [[ "$force_removal" != "true" ]]; then
        printf "Remove installation? (y/N): "
        read -r confirm
        if [[ "$confirm" != [yY] ]]; then
            printf "Uninstall cancelled.\n"
            return 0
        fi
    fi
    
    printf "\n%sRemoving installation...%s\n" "$yellow" "$x"
    
    # Remove symlink
    local bin_symlink="$bin_dir/$install_id"
    if [[ -L "$bin_symlink" ]]; then
        printf "%s  Removing symlink: %s%s\n" "$green" "$bin_symlink" "$x"
        rm -f "$bin_symlink"
    fi
    
    # Remove installed files
    if [[ -f "$install_path" ]]; then
        printf "%s  Removing script: %s%s\n" "$green" "$install_path" "$x"
        rm -f "$install_path"
    fi
    
    # Remove config if it exists
    local config_path="$(dirname "$install_path")/build.conf"
    if [[ -f "$config_path" ]]; then
        printf "%s  Removing config: %s%s\n" "$green" "$config_path" "$x"
        rm -f "$config_path"
    fi
    
    # Clean up empty directories
    local install_dir="$(dirname "$install_path")"
    if [[ -d "$install_dir" ]] && [[ -z "$(ls -A "$install_dir" 2>/dev/null)" ]]; then
        printf "%s  Removing empty directory: %s%s\n" "$green" "$install_dir" "$x"
        rmdir "$install_dir" 2>/dev/null || true
    fi
    
    # Remove from registry
    remove_installation_record "$registry" "$install_id"
    
    printf "\n%s✓ Uninstall complete!%s\n" "$green" "$x"
    return 0
}

