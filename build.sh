# Routes subcommands to appropriate do_* functions
# Handles both new subcommand style and legacy flag compatibility
dispatch() {
    local subcommand="${1:-}"
    shift || true
    
    # Handle legacy compatibility mode first
    if [[ -n "${_compat_mode:-}" ]]; then
        if [[ "$opt_quiet" != true ]]; then
            printf "%sNOTE:%s Using legacy flag mode. Consider using subcommands instead.\n" "$yellow" "$x" >&2
        fi
        case "$_compat_mode" in
            (insert)
                do_insert "${_compat_args[@]}"
                ;;
            (swap)
                do_swap "${_compat_args[@]}"
                ;;
            (remap)
                do_remap
                ;;
            (list)
                do_list
                ;;
        esac
        return $?
    fi
    
    # Handle help request
    if [[ "${_help_requested:-false}" == true ]]; then
        usage "$subcommand" "$@"
        return 0
    fi
    
    # Handle version request
    if [[ "${_version_requested:-false}" == true ]]; then
        do_version
        return 0
    fi
    
    # Default to build if no subcommand
    [[ -z "$subcommand" ]] && subcommand="build"
    
    # Route to appropriate do_* function
    case "$subcommand" in
        (build)
            do_build "$@"
            ;;
        (insert)
            do_insert "$@"
            ;;
        (swap)
            do_swap "$@"
            ;;
        (list)
            do_list "$@"
            ;;
        (remap)
            do_remap "$@"
            ;;
        (restore)
            do_restore "$@"
            ;;
        (version)
            do_version "$@"
            ;;
        (logo)
            do_logo "$@"
            ;;
        (install)
            do_install "$@"
            ;;
        (uninstall)
            do_uninstall "$@"
            ;;
        (deploy)
            do_deploy "$@"
            ;;
        (status)
            do_status "$@"
            ;;
        (test)
            do_test "$@"
            ;;
        (help)
            usage "$@"
            ;;
        (*)
            printf "%sERROR:%s Unknown subcommand: %s\n" "$red" "$x" "$subcommand" >&2
            printf "Run '%s help' for usage information\n" "$(basename "$0")" >&2
            return 1
            ;;
    esac
}

