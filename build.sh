                printf " (%d lines)\n" "$lines"
                ((count++))
            fi
        done < <(find "$PARTS_DIR" -name "[0-9]*_*.sh" -print0 | sort -z)
    fi
    
    printf "\n%sTotal modules: %d%s\n" "$blue" "$count" "$x"
    return 0
